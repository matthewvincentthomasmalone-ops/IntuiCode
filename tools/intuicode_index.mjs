// The IntuCode index: every sentence pattern and word phrase the writers export (TEMPLATES, WORDS, GUIDE…),
// by language and topic, with what each becomes. Written into INTUICODE.md (between the index markers) and
// lang/intuicode_index.json (for the app's Index).
//   node tools/intuicode_index.mjs           rewrite both
//   node tools/intuicode_index.mjs --check   exit 1 if either is out of date (npm test runs this check)
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadEngine, ROOT } from '../tests/helpers/engine.mjs';

export const DOC = path.join(ROOT, 'INTUICODE.md');
export const JSON_FILE = path.join(ROOT, 'lang', 'intuicode_index.json');
export const START = '<!-- index:start: generated by node tools/intuicode_index.mjs; do not edit by hand -->';
export const END = '<!-- index:end -->';

/* Each folder's name and the code file it becomes, as app.js names them (SECTION_META, FILE_NAME). A sketch is
   named after its project folder (blink/blink.ino). */
export const FOLDERS = {
  settings: ['Settings', 'settings.py'], tools: ['Tools', 'tools.py'], main: ['Main program', 'main.py'],
  structure: ['Structure', 'index.html'], styling: ['Styling', 'style.css'], mechanics: ['Mechanics', 'script.js'],
  program: ['Program', 'main.cpp'], sketch: ['Sketch', '‹folder›.ino'],
};

const plain = (x) => JSON.parse(JSON.stringify(x));
const folder = (id, about) => ({ id, name: FOLDERS[id][0], file: FOLDERS[id][1], about: about || '' });
const sentences = (templates, folders) => plain(templates)
  .filter(t => t.sections.some(s => folders.includes(s)))
  .map(t => ({ topic: t.group, say: t.pattern, becomes: t.py, folders: t.sections.filter(s => folders.includes(s)), tip: t.tip || '' }));
const words = (pairs) => plain(pairs).map(([say, becomes]) => ({ say, becomes }));
/* The phrases a regular expression made of words, | and (?:…) groups matches: first(?:ly)? -> first, firstly. */
function phrases(src) {
  const alts = [];
  let depth = 0, cur = '';
  for (const c of src) {
    if (c === '|' && !depth) { alts.push(cur); cur = ''; continue; }
    if (c === '(') depth++; else if (c === ')') depth--;
    cur += c;
  }
  alts.push(cur);
  return alts.flatMap((alt) => {
    let outs = [''];
    for (let i = 0; i < alt.length;) {
      if (!alt.startsWith('(?:', i)) { outs = outs.map(o => o + alt[i]); i++; continue; }
      let d = 1, j = i + 3;
      for (; j < alt.length && d; j++) { if (alt[j] === '(') d++; else if (alt[j] === ')') d--; }
      let opts = phrases(alt.slice(i + 3, j - 1));
      if (alt[j] === '?') { opts = ['', ...opts]; j++; }
      outs = outs.flatMap(o => opts.map(p => o + p));
      i = j;
    }
    return outs;
  });
}
/* The words of a filler regular expression like ^(?:(?:please|first(?:ly)?|…)\s*,?\s+)+ */
const fillerWords = (re) => phrases(re.source.replace(/^\^\(\?:\(\?:/, '').replace(/\)\\s\*,\?\\s\+\)\+$/, ''));

export function buildIndex() {
  const { L, WEB, CPP } = loadEngine();
  return {
    about: 'Generated by tools/intuicode_index.mjs from the data the writers export. Do not edit by hand: run node tools/intuicode_index.mjs.',
    languages: [
      {
        id: 'python', name: 'Python', writer: 'lang/python.js',
        folders: ['settings', 'tools', 'main'].map(f => folder(f, L.GUIDE.sections[f])),
        sentences: sentences(L.TEMPLATES, ['settings', 'tools', 'main']),
        words: words(L.WORDS),
        examples: plain(L.GUIDE.howtos).map(([title, say]) => ({ title, say })),
        filler: { atTheStart: fillerWords(L.FILLER.lead), anywhere: plain(L.FILLER.words) },
        notNames: [...L.keywords.python].sort(),
      },
      {
        id: 'html', name: 'HTML', writer: 'lang/web_write.js',
        folders: [folder('structure', WEB.GUIDES.structure.section)],
        sentences: sentences(WEB.TEMPLATES, ['structure']),
        words: words(WEB.WORDS.structure),
      },
      {
        id: 'css', name: 'CSS', writer: 'lang/web_write.js',
        folders: [folder('styling', WEB.GUIDES.styling.section)],
        sentences: sentences(WEB.TEMPLATES, ['styling']),
        words: words(WEB.WORDS.styling),
        selectors: Object.entries(plain(WEB.TAG_WORDS)).map(([say, becomes]) => ({ say, becomes })),
      },
      {
        id: 'js', name: 'JavaScript', writer: 'lang/web_write.js',
        folders: [folder('mechanics', WEB.GUIDES.mechanics.section)],
        sentences: sentences(WEB.TEMPLATES, ['mechanics']),
        words: words(WEB.WORDS.mechanics),
      },
      {
        id: 'cpp', name: 'C++', writer: 'lang/cpp_write.js',
        folders: [folder('program', CPP.GUIDE.section)],
        sentences: sentences(CPP.TEMPLATES, ['program']),
        words: words(CPP.WORDS),
      },
      {
        id: 'arduino', name: 'Arduino', writer: 'lang/cpp_write.js',
        folders: [folder('sketch', CPP.ARDUINO_GUIDE.section)],
        sentences: sentences(CPP.TEMPLATES, ['sketch']),
        words: words(CPP.ARDUINO_WORDS),
      },
    ],
  };
}

/* Markdown --------------------------------------------------------------------------------------------- */

/* Inline code that survives any backticks inside it; | is escaped for tables. */
function ic(s) {
  s = String(s);
  const run = Math.max(0, ...(s.match(/`+/g) || []).map(r => r.length));
  const fence = '`'.repeat(run + 1), pad = /^`|`$/.test(s) ? ' ' : '';
  return (fence + pad + s + pad + fence).replace(/\|/g, '\\|');
}
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const folderNames = (ids) => ids.map(f => FOLDERS[f][0]).join(', ');

function table(head, rows) {
  return [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map(r => `| ${r.join(' | ')} |`)].join('\n');
}

export function renderIndex(index) {
  const out = [];
  out.push('This part is generated by `node tools/intuicode_index.mjs` from the data the writers export for the phrase picker',
    'and the app\'s Index (`TEMPLATES`, `WORDS`, `GUIDE`, `TAG_WORDS`, `FILLER`, `keywords`). The same data is in',
    '`lang/intuicode_index.json`. Don\'t edit it by hand: change the writer, then run the script. `npm test` fails while',
    'it is out of date. The patterns here are the usual ways to say each thing; the grammar above lists every form,',
    'synonyms included.', '');
  for (const lang of index.languages) {
    const files = lang.folders.map(f => `${f.name} → \`${f.file}\``).join(', ');
    out.push(`### ${lang.name}`, '', `${files}. Writer: \`${lang.writer}\`.`, '');
    for (const f of lang.folders) if (f.about) out.push(`- **${f.name}:** ${f.about}`);
    if (lang.folders.some(f => f.about)) out.push('');
    const many = lang.folders.length > 1;
    let topic = null;
    const rows = lang.sentences.map(s => {
      const t = s.topic === topic ? '' : `**${cell(s.topic)}**`;
      topic = s.topic;
      return [t, ic(s.say), ic(s.becomes), ...(many ? [folderNames(s.folders)] : []), cell(s.tip)];
    });
    out.push(`#### ${lang.name} sentences`, '', table(['Topic', 'Say', 'Becomes', ...(many ? ['Folders'] : []), 'Note'], rows), '');
    if (lang.words.length) out.push(`#### ${lang.name} words inside sentences`, '', table(['Say', 'Becomes'], lang.words.map(w => [ic(w.say), ic(w.becomes)])), '');
    if (lang.selectors) out.push(`#### ${lang.name}: words for what to style`, '', table(['Say', 'Selector'], lang.selectors.map(w => [ic(w.say), ic(w.becomes)])), '');
    if (lang.examples) {
      out.push(`#### ${lang.name} examples (the Index's how-tos)`, '');
      for (const e of lang.examples) out.push(`**${e.title}**`, '', '```', e.say, '```', '');
    }
    if (lang.filler) {
      out.push(`#### ${lang.name} filler words`, '',
        `- Left out at the start of a line: ${lang.filler.atTheStart.map(w => ic(w)).join(', ')}.`,
        `- Left out anywhere outside quotes: ${lang.filler.anywhere.map(w => ic(w)).join(', ')}.`, '');
    }
    if (lang.notNames) out.push(`Python's own words, which can't be names: ${lang.notNames.map(w => ic(w)).join(', ')}.`, '');
  }
  return out.join('\n').replace(/\n+$/, '');
}

/* The files as they should be ------------------------------------------------------------------------- */

const lf = (s) => s.replace(/\r\n/g, '\n');

export function expectedFiles() {
  const index = buildIndex();
  const doc = lf(readFileSync(DOC, 'utf8'));
  const a = doc.indexOf(START), b = doc.indexOf(END);
  if (a < 0 || b < a) throw new Error(`INTUICODE.md has no index markers:\n${START}\n${END}`);
  return {
    doc: doc.slice(0, a + START.length) + '\n\n' + renderIndex(index) + '\n\n' + doc.slice(b),
    json: JSON.stringify(index, null, 2) + '\n',
  };
}

/* Which files are out of date? -> [] when both are current. */
export function outOfDate() {
  const want = expectedFiles(), stale = [];
  if (lf(readFileSync(DOC, 'utf8')) !== want.doc) stale.push('INTUICODE.md');
  let json = null;
  try { json = lf(readFileSync(JSON_FILE, 'utf8')); } catch (_) { /* missing */ }
  if (json !== want.json) stale.push('lang/intuicode_index.json');
  return stale;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const stale = outOfDate();
    if (stale.length) { console.error(`Out of date: ${stale.join(', ')}. Run: node tools/intuicode_index.mjs`); process.exit(1); }
    console.log('The IntuCode index is up to date.');
  } else {
    const want = expectedFiles();
    const crlf = /\r\n/.test(readFileSync(DOC, 'utf8'));   // keep the file's own line endings
    writeFileSync(DOC, crlf ? want.doc.replace(/\n/g, '\r\n') : want.doc);
    writeFileSync(JSON_FILE, want.json);
    console.log('Wrote the index into INTUICODE.md and lang/intuicode_index.json.');
  }
}
